"""Generate egl_probe's extension -> entry point table from the NDK headers plus extra_procs.txt.

Usage: gen_procs.py <ndk-include-dir> <extra_procs.txt> <out.h>
Each `#define <EXT> 1` in EGL/eglext.h, GLES/glext.h, GLES2/gl2ext.h opens an extension; every prototype
`... APIENTRY name (` after it belongs to that extension. extra_procs.txt adds lines `api ext function` for
extensions the r9 headers lack or that reuse another extension's entry points.
"""
import re
import sys

HEADERS = (("egl", "EGL/eglext.h"), ("gles1", "GLES/glext.h"), ("gles2", "GLES2/gl2ext.h"))
EXT_RE = re.compile(r"^#define\s+((?:GL|EGL)_[A-Z0-9]+_\w+)\s+1\s*$")
FN_RE = re.compile(r"APIENTRY\s+(\w+)\s*\(")


def main():
    inc, extra, out = sys.argv[1:4]
    rows = []
    for api, rel in HEADERS:
        ext = None
        with open(f"{inc}/{rel}") as f:
            for line in f:
                m = EXT_RE.match(line)
                if m:
                    ext = m.group(1)
                    continue
                if line.lstrip().startswith("typedef"):
                    continue
                m = FN_RE.search(line)
                if m and ext:
                    rows.append((api, ext, m.group(1)))
    with open(extra) as f:
        for line in f:
            line = line.split("#", 1)[0].split()
            if line:
                rows.append(tuple(line[:3]))
    seen = set()
    uniq = []
    for r in rows:
        if r not in seen:
            seen.add(r)
            uniq.append(r)
    uniq.sort()
    with open(out, "w") as f:
        f.write("/* generated by gen_procs.py from the NDK headers + extra_procs.txt; do not edit */\n")
        f.write("static const struct ext_proc k_procs[] = {\n")
        for api, ext, fn in uniq:
            f.write(f'  {{"{api}", "{ext}", "{fn}"}},\n')
        f.write("};\n")
    print(f"{out}: {len(uniq)} entries", file=sys.stderr)


if __name__ == "__main__":
    main()
