static int bpp(GLenum fmt, GLenum type) {
  if (type == GL_UNSIGNED_BYTE) {
    switch (fmt) {
      case GL_ALPHA: case GL_LUMINANCE: return 1;
      case GL_LUMINANCE_ALPHA: return 2;
      case GL_RGB: return 3;
      default: return 4;
    }
  }
  if (type == GL_FLOAT) return 16;
  return 2;
}

static int job_readpixels(void) {
  struct env e;
  if (!env_make(&e, 2)) { check("readpixels", "FAIL", "no ES2 context"); return 1; }
  while (glGetError() != GL_NO_ERROR) {}
  glBindFramebuffer(GL_FRAMEBUFFER, 0);
  glViewport(0, 0, PB_W, PB_H);
  glClearColor(64 / 255.f, 128 / 255.f, 192 / 255.f, 1.f);
  glClear(GL_COLOR_BUFFER_BIT);
  GLubyte px[4] = {0, 0, 0, 0};
  glPixelStorei(GL_PACK_ALIGNMENT, 1);
  glReadPixels(PB_W / 2, PB_H / 2, 1, 1, GL_RGBA, GL_UNSIGNED_BYTE, px);
  GLenum err = glGetError();
  EGLint rs = 0, gs = 0, bs = 0;
  eglGetConfigAttrib(e.d, e.cfg, EGL_RED_SIZE, &rs);
  eglGetConfigAttrib(e.d, e.cfg, EGL_GREEN_SIZE, &gs);
  eglGetConfigAttrib(e.d, e.cfg, EGL_BLUE_SIZE, &bs);
  int tol = (rs < 8 || gs < 8 || bs < 8) ? 9 : 2;
  int ok = !err && abs(px[0] - 64) <= tol && abs(px[1] - 128) <= tol && abs(px[2] - 192) <= tol && px[3] >= 250;
  check("readpixels-rgba-ubyte", ok ? "PASS" : "FAIL", "err %s; got %02x%02x%02x%02x want 4080c0ff (+-%d); surface R%dG%dB%d",
        glerr(err), px[0], px[1], px[2], px[3], tol, rs, gs, bs);
  GLint f = 0, t = 0;
  glGetIntegerv(GL_IMPLEMENTATION_COLOR_READ_FORMAT, &f);
  glGetIntegerv(GL_IMPLEMENTATION_COLOR_READ_TYPE, &t);
  err = glGetError();
  GLubyte buf[4 * 4 * 16];
  memset(buf, 0, sizeof buf);
  if (!err) {
    glReadPixels(0, 0, 4, 4, f, t, buf);
    err = glGetError();
  }
  int b = bpp(f, t);
  char hex[64] = "";
  for (int k = 0; k < b && k < 16; k++) snprintf(hex + strlen(hex), sizeof hex - strlen(hex), "%02x", buf[k]);
  check("readpixels-implementation-format", err ? "FAIL" : "PASS", "format 0x%04x %s, type 0x%04x %s; err %s; first pixel %s",
        (unsigned)f, fmtname(f), (unsigned)t, fmtname(t), glerr(err), hex);
  env_free(&e);
  return 0;
}

static int job_maxtex(void) {
  struct env e;
  if (!env_make(&e, 2)) { check("max-texture", "FAIL", "no ES2 context"); return 1; }
  GLint m = 0;
  glGetIntegerv(GL_MAX_TEXTURE_SIZE, &m);
  while (glGetError() != GL_NO_ERROR) {}
  GLuint tex, fb;
  glGenTextures(1, &tex);
  glBindTexture(GL_TEXTURE_2D, tex);
  glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MIN_FILTER, GL_NEAREST);
  glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_WRAP_S, GL_CLAMP_TO_EDGE);
  glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_WRAP_T, GL_CLAMP_TO_EDGE);
  glTexImage2D(GL_TEXTURE_2D, 0, GL_RGBA, m, m, 0, GL_RGBA, GL_UNSIGNED_BYTE, NULL);
  GLenum te = glGetError();
  /* glTexImage2D(NULL) may defer the allocation: render into the whole texture and read a far corner back. */
  glGenFramebuffers(1, &fb);
  glBindFramebuffer(GL_FRAMEBUFFER, fb);
  glFramebufferTexture2D(GL_FRAMEBUFFER, GL_COLOR_ATTACHMENT0, GL_TEXTURE_2D, tex, 0);
  GLenum st = glCheckFramebufferStatus(GL_FRAMEBUFFER);
  GLubyte px[4] = {0, 0, 0, 0};
  GLenum de = GL_NO_ERROR;
  if (st == GL_FRAMEBUFFER_COMPLETE) {
    glViewport(0, 0, m, m);
    glClearColor(1.f, 0.f, 1.f, 1.f);
    glClear(GL_COLOR_BUFFER_BIT);
    glReadPixels(m - 1, m - 1, 1, 1, GL_RGBA, GL_UNSIGNED_BYTE, px);
    glFinish();
    de = glGetError();
  }
  int ok = !te && st == GL_FRAMEBUFFER_COMPLETE && !de && px[0] > 200 && px[1] < 50 && px[2] > 200;
  check("max-texture-rgba8-alloc", ok ? "PASS" : "FAIL",
        "%dx%d RGBA8 (%lld MiB): teximage %s; fbo %s; clear+read %s; corner pixel %02x%02x%02x%02x", m, m,
        (long long)m * m * 4 / 1048576, glerr(te), fboname(st), glerr(de), px[0], px[1], px[2], px[3]);
  glBindFramebuffer(GL_FRAMEBUFFER, 0);
  glDeleteFramebuffers(1, &fb);
  glDeleteTextures(1, &tex);
  env_free(&e);
  return 0;
}

