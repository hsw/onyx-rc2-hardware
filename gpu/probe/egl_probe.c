/* The original (v1) probe, output unchanged: scripts grep its keys. */
static int job_q3(void) {
  EGLDisplay d = eglGetDisplay(EGL_DEFAULT_DISPLAY);
  EGLint maj = 0, min = 0;
  if (d == EGL_NO_DISPLAY || !eglInitialize(d, &maj, &min)) {
    printf("egl_init: FAIL 0x%x\n", eglGetError());
    return 1;
  }
  printf("egl_version: %d.%d\n", maj, min);
  printf("egl_vendor: %s\n", eglQueryString(d, EGL_VENDOR));
  printf("egl_version_string: %s\n", eglQueryString(d, EGL_VERSION));
  printf("egl_client_apis: %s\n", eglQueryString(d, EGL_CLIENT_APIS));
  const char *eext = eglQueryString(d, EGL_EXTENSIONS);
  list("egl_extensions", eext);

  /* Chromium first asks for an ES3 config, then ES2 (gl_surface_egl.cc). */
  EGLint es3[] = {EGL_RENDERABLE_TYPE, EGL_OPENGL_ES3_BIT_KHR, EGL_NONE};
  EGLint n = 0;
  EGLBoolean ok = eglChooseConfig(d, es3, NULL, 0, &n);
  printf("es3_config: %s n=%d err=0x%x\n", ok ? "ok" : "FAIL", n, ok ? 0 : eglGetError());

  EGLint attr[] = {EGL_RENDERABLE_TYPE, EGL_OPENGL_ES2_BIT, EGL_SURFACE_TYPE, EGL_PBUFFER_BIT,
                   EGL_RED_SIZE, 8, EGL_GREEN_SIZE, 8, EGL_BLUE_SIZE, 8, EGL_ALPHA_SIZE, 8, EGL_NONE};
  EGLConfig cfg;
  if (!eglChooseConfig(d, attr, &cfg, 1, &n) || n < 1) {
    printf("es2_pbuffer_config: FAIL 0x%x\n", eglGetError());
    return 1;
  }
  printf("es2_pbuffer_config: ok\n");
  EGLint pb[] = {EGL_WIDTH, 16, EGL_HEIGHT, 16, EGL_NONE};
  EGLSurface s = eglCreatePbufferSurface(d, cfg, pb);
  EGLint ca[] = {EGL_CONTEXT_CLIENT_VERSION, 2, EGL_NONE};
  EGLContext c = eglCreateContext(d, cfg, EGL_NO_CONTEXT, ca);
  if (s == EGL_NO_SURFACE || c == EGL_NO_CONTEXT || !eglMakeCurrent(d, s, s, c)) {
    printf("es2_context: FAIL 0x%x\n", eglGetError());
    return 1;
  }
  printf("es2_context: ok\n");
  /* Second context sharing with the first: what a WebView GL functor would need. */
  EGLContext c2 = eglCreateContext(d, cfg, c, ca);
  printf("shared_context: %s\n", c2 != EGL_NO_CONTEXT ? "ok" : "FAIL");

  printf("gl_vendor: %s\n", (const char *)glGetString(GL_VENDOR));
  printf("gl_renderer: %s\n", (const char *)glGetString(GL_RENDERER));
  printf("gl_version: %s\n", (const char *)glGetString(GL_VERSION));
  printf("gl_shading_language: %s\n", (const char *)glGetString(GL_SHADING_LANGUAGE_VERSION));
  const char *gext = (const char *)glGetString(GL_EXTENSIONS);
  list("gl_extensions", gext);
  GLint v = 0;
  glGetIntegerv(GL_MAX_TEXTURE_SIZE, &v); printf("max_texture_size: %d\n", v);
  glGetIntegerv(GL_MAX_RENDERBUFFER_SIZE, &v); printf("max_renderbuffer_size: %d\n", v);
  glGetIntegerv(GL_MAX_TEXTURE_IMAGE_UNITS, &v); printf("max_texture_image_units: %d\n", v);

  /* Chromium gpu_info_collector.cc: can_support_threaded_texture_mailbox. */
  int mb = has(eext, "EGL_KHR_fence_sync") && has(eext, "EGL_KHR_image_base") &&
           has(eext, "EGL_KHR_gl_texture_2D_image") && has(gext, "GL_OES_EGL_image");
  printf("threaded_texture_mailbox_exts: %s\n", mb ? "yes" : "no");

  /* Functional checks, not just the strings. */
  PFNEGLCREATESYNCKHRPROC cs = (PFNEGLCREATESYNCKHRPROC)eglGetProcAddress("eglCreateSyncKHR");
  PFNEGLCLIENTWAITSYNCKHRPROC ws = (PFNEGLCLIENTWAITSYNCKHRPROC)eglGetProcAddress("eglClientWaitSyncKHR");
  PFNEGLDESTROYSYNCKHRPROC ds = (PFNEGLDESTROYSYNCKHRPROC)eglGetProcAddress("eglDestroySyncKHR");
  if (cs && ws && ds) {
    EGLSyncKHR f = cs(d, EGL_SYNC_FENCE_KHR, NULL);
    EGLint r = f != EGL_NO_SYNC_KHR ? ws(d, f, EGL_SYNC_FLUSH_COMMANDS_BIT_KHR, 1000000000ull) : 0;
    printf("fence_sync: %s wait=0x%x\n", f != EGL_NO_SYNC_KHR ? "ok" : "FAIL", r);
    if (f != EGL_NO_SYNC_KHR) ds(d, f);
  } else {
    printf("fence_sync: no entry points\n");
  }

  PFNEGLCREATEIMAGEKHRPROC ci = (PFNEGLCREATEIMAGEKHRPROC)eglGetProcAddress("eglCreateImageKHR");
  PFNEGLDESTROYIMAGEKHRPROC di = (PFNEGLDESTROYIMAGEKHRPROC)eglGetProcAddress("eglDestroyImageKHR");
  PFNGLEGLIMAGETARGETTEXTURE2DOESPROC tt =
      (PFNGLEGLIMAGETARGETTEXTURE2DOESPROC)eglGetProcAddress("glEGLImageTargetTexture2DOES");
  if (ci && di && tt) {
    GLuint t[2];
    glGenTextures(2, t);
    glBindTexture(GL_TEXTURE_2D, t[0]);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MIN_FILTER, GL_LINEAR);
    glTexImage2D(GL_TEXTURE_2D, 0, GL_RGBA, 16, 16, 0, GL_RGBA, GL_UNSIGNED_BYTE, NULL);
    EGLImageKHR img = ci(d, c, EGL_GL_TEXTURE_2D_KHR, (EGLClientBuffer)(unsigned long)t[0], NULL);
    printf("egl_image_from_texture: %s err=0x%x\n", img != EGL_NO_IMAGE_KHR ? "ok" : "FAIL",
           img != EGL_NO_IMAGE_KHR ? 0 : eglGetError());
    if (img != EGL_NO_IMAGE_KHR) {
      glBindTexture(GL_TEXTURE_2D, t[1]);
      tt(GL_TEXTURE_2D, (GLeglImageOES)img);
      printf("egl_image_target_texture: %s gl_err=0x%x\n", glGetError() == GL_NO_ERROR ? "ok" : "FAIL",
             glGetError());
      di(d, img);
    }
    glDeleteTextures(2, t);
  } else {
    printf("egl_image: no entry points\n");
  }

  eglMakeCurrent(d, EGL_NO_SURFACE, EGL_NO_SURFACE, EGL_NO_CONTEXT);
  if (c2 != EGL_NO_CONTEXT) eglDestroyContext(d, c2);
  eglDestroyContext(d, c);
  eglDestroySurface(d, s);
  eglTerminate(d);
  return 0;
}

