/* ------------------------------------------------------------------ EGL setup */

struct env { EGLDisplay d; EGLConfig cfg; EGLSurface s; EGLContext c; const char *gext; };

/* Context of client version `ver` (1 or 2) on a PB_W x PB_H pbuffer; RGBA8888 if there is one. */
static int env_make(struct env *e, int ver) {
  memset(e, 0, sizeof *e);
  e->d = eglGetDisplay(EGL_DEFAULT_DISPLAY);
  EGLint maj, min;
  if (e->d == EGL_NO_DISPLAY || !eglInitialize(e->d, &maj, &min)) {
    printf("error\teglInitialize 0x%x\n", eglGetError());
    return 0;
  }
  EGLint bit = ver == 1 ? EGL_OPENGL_ES_BIT : EGL_OPENGL_ES2_BIT;
  EGLint a8[] = {EGL_RENDERABLE_TYPE, bit, EGL_SURFACE_TYPE, EGL_PBUFFER_BIT, EGL_RED_SIZE, 8, EGL_GREEN_SIZE, 8,
                 EGL_BLUE_SIZE, 8, EGL_ALPHA_SIZE, 8, EGL_NONE};
  EGLint any[] = {EGL_RENDERABLE_TYPE, bit, EGL_SURFACE_TYPE, EGL_PBUFFER_BIT, EGL_NONE};
  EGLint n = 0;
  if (!eglChooseConfig(e->d, a8, &e->cfg, 1, &n) || n < 1) {
    n = 0;
    if (!eglChooseConfig(e->d, any, &e->cfg, 1, &n) || n < 1) {
      printf("error\tno ES%d pbuffer config 0x%x\n", ver, eglGetError());
      return 0;
    }
  }
  EGLint pb[] = {EGL_WIDTH, PB_W, EGL_HEIGHT, PB_H, EGL_NONE};
  e->s = eglCreatePbufferSurface(e->d, e->cfg, pb);
  EGLint ca[] = {EGL_CONTEXT_CLIENT_VERSION, ver, EGL_NONE};
  e->c = eglCreateContext(e->d, e->cfg, EGL_NO_CONTEXT, ca);
  if (e->s == EGL_NO_SURFACE || e->c == EGL_NO_CONTEXT || !eglMakeCurrent(e->d, e->s, e->s, e->c)) {
    printf("error\tES%d context/pbuffer 0x%x\n", ver, eglGetError());
    return 0;
  }
  e->gext = (const char *)glGetString(GL_EXTENSIONS);
  return 1;
}

static void env_free(struct env *e) {
  if (e->d == EGL_NO_DISPLAY) return;
  eglMakeCurrent(e->d, EGL_NO_SURFACE, EGL_NO_SURFACE, EGL_NO_CONTEXT);
  if (e->c != EGL_NO_CONTEXT) eglDestroyContext(e->d, e->c);
  if (e->s != EGL_NO_SURFACE) eglDestroySurface(e->d, e->s);
  eglTerminate(e->d);
}

/* ------------------------------------------------------------------ vendor driver */

typedef void (*vfn)(void);
typedef vfn (*gpa_fn)(const char *);
static char g_vendor_path[256];

/* The driver libEGL.so loads: the last non-"android" tag of egl.cfg, else "mali", else "emulation". */
static void *vendor_open(void) {
  static const char *dirs[] = {"/vendor/lib/egl", "/system/lib/egl"};
  static const char *pre[] = {"libEGL_", "libGLES_"};
  char tag[64] = "", t[64];
  FILE *f = fopen("/system/lib/egl/egl.cfg", "r");
  if (f) {
    int dpy, impl;
    while (fscanf(f, "%d %d %63s", &dpy, &impl, t) == 3)
      if (strcmp(t, "android")) snprintf(tag, sizeof tag, "%s", t);
    fclose(f);
  }
  const char *tags[] = {tag, "mali", "emulation"};
  for (size_t k = 0; k < NELEM(tags); k++) {
    if (!tags[k][0]) continue;
    for (size_t i = 0; i < NELEM(dirs); i++)
      for (size_t j = 0; j < NELEM(pre); j++) {
        snprintf(g_vendor_path, sizeof g_vendor_path, "%s/%s%s.so", dirs[i], pre[j], tags[k]);
        if (access(g_vendor_path, R_OK)) continue;
        void *h = dlopen(g_vendor_path, RTLD_NOW);
        if (h) return h;
      }
  }
  g_vendor_path[0] = 0;
  return NULL;
}

static gpa_fn vendor_gpa(void) {
  static int done;
  static gpa_fn g;
  if (!done) {
    done = 1;
    void *h = vendor_open();
    if (h) g = (gpa_fn)dlsym(h, "eglGetProcAddress");
  }
  return g;
}

