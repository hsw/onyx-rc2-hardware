static void gl_strings(const char *api, int es2) {
  struct { const char *k; GLenum e; } s[] = {{"GL_VENDOR", GL_VENDOR},
                                             {"GL_RENDERER", GL_RENDERER},
                                             {"GL_VERSION", GL_VERSION},
                                             {"GL_SHADING_LANGUAGE_VERSION", GL_SHADING_LANGUAGE_VERSION}};
  for (size_t i = 0; i < NELEM(s); i++) {
    if (!es2 && s[i].e == GL_SHADING_LANGUAGE_VERSION) {
      printf("%s\tn/a (ES 1.1)\n", s[i].k);
      continue;
    }
    while (glGetError() != GL_NO_ERROR) {}
    const char *v = (const char *)glGetString(s[i].e);
    if (v) printf("%s\t%s\n", s[i].k, v);
    else printf("%s\t(null %s)\n", s[i].k, glerr(glGetError()));
    tsvf(T_LIMITS, "%s\t%s\t%s\n", api, s[i].k, v ? v : "(null)");
  }
}

