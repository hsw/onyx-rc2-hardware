/* egl_probe: inventory of EGL / GLES 1.1 / GLES 2.0 support on an Android 4.4 device (RC2: Mali-400 MP r3p2),
 * plus the EGL/GLES2 facts Chromium M83 checks (section chromium-q3, the original probe's lines unchanged).
 * Run as shell or root over adb (needs /dev/mali readable; stock RK30 ueventd: 0666).
 *
 * Usage: egl_probe [--tsv DIR] [--only JOB] [--skip-maxtex] [--list]
 * Output: plain text, `## <section>` headers, tab-separated lines, no pointers or timings, so two runs diff cleanly.
 * Every job (q3, egl, egl-vendor, gles1, gles2, one per functional check) runs in a forked child with an alarm;
 * the parent never touches EGL, reports a crash or timeout in `## summary` and goes on with the next job.
 * --tsv DIR writes configs.tsv, extensions.tsv, limits.tsv, procs.tsv, checks.tsv (DIR is created).
 *
 * Two EGL layers: the app side (libEGL.so) is Android's META-EGL: EGL_VENDOR/VERSION/CLIENT_APIS are its own
 * strings, EGL_EXTENSIONS is the driver list filtered by a whitelist, and eglGetProcAddress returns libEGL's own
 * wrapper for names in its table (note "libEGL-wrapper") and NULL for its blocked names ("libEGL-filtered").
 * The egl-vendor job dlopens the driver (egl.cfg tag, e.g. /system/lib/egl/libEGL_mali.so) and asks it directly. */
