/* libEGL 4.4 (frameworks/native/opengl/libs/EGL/eglApi.cpp sExtensionMap / FILTER_EXTENSIONS). */
static const char *k_wrapped[] = {
    "eglLockSurfaceKHR", "eglUnlockSurfaceKHR", "eglCreateImageKHR", "eglDestroyImageKHR", "eglCreateSyncKHR",
    "eglDestroySyncKHR", "eglGetRenderBufferANDROID", "eglRenderBufferModifiedANDROID", "eglSetImplementationAndroid",
    "eglClientWaitSyncKHR", "eglSignalSyncKHR", "eglGetSyncAttribKHR", "eglGetSystemTimeFrequencyNV",
    "eglGetSystemTimeNV", "eglWaitSyncKHR", "eglPresentationTimeANDROID"};
static const char *k_filtered[] = {"eglSetBlobCacheFuncsANDROID", "eglHibernateProcessIMG", "eglAwakenProcessIMG",
                                   "eglDupNativeFenceFDANDROID"};
static int in(const char *const *t, size_t n, const char *s) {
  for (size_t i = 0; i < n; i++)
    if (!strcmp(t[i], s)) return 1;
  return 0;
}

static const char *nn(vfn p) { return p ? "non-NULL" : "NULL"; }

/* layer "app": libEGL's eglGetProcAddress; "vendor": the driver's own; "both": GL names, app + vendor columns. */
static void procs_api(const char *api, const char *exts, const char *layer, gpa_fn vgpa, const char *sec_adv,
                      const char *sec_unadv) {
  int found = 0;
  for (int pass = 0; pass < 2; pass++) {
    section(pass ? sec_unadv : sec_adv);
    if (pass == 0) {
      /* Advertised extensions with no entry in the table: list them, so nothing is silently skipped. */
      static char buf[16384];
      char *v[1024];
      int n = 0;
      snprintf(buf, sizeof buf, "%s", exts ? exts : "");
      for (char *t = strtok(buf, " "); t && n < (int)NELEM(v); t = strtok(NULL, " ")) v[n++] = t;
      qsort(v, n, sizeof v[0], cmpstr);
      for (int i = 0; i < n; i++) {
        int any = 0;
        for (size_t k = 0; k < NELEM(k_procs) && !any; k++)
          any = !strcmp(k_procs[k].api, api) && !strcmp(k_procs[k].ext, v[i]);
        if (!any) printf("%s\t(no entry points in the probe's table)\n", v[i]);
      }
    }
    for (size_t k = 0; k < NELEM(k_procs); k++) {
      const struct ext_proc *p = &k_procs[k];
      if (strcmp(p->api, api)) continue;
      int adv = has(exts, p->ext);
      if (adv != !pass) continue;
      const char *note = "";
      if (!strcmp(layer, "vendor")) {
        vfn r = vgpa ? vgpa(p->fn) : NULL;
        printf("%s\t%s\tvendor=%s\n", p->ext, p->fn, vgpa ? nn(r) : "(no driver)");
        tsvf(T_PROCS, "%s\tvendor\t%s\t%s\t%s\t%s\t\n", api, p->ext, p->fn, adv ? "yes" : "no",
             vgpa ? nn(r) : "no-driver");
        continue;
      }
      vfn a = eglGetProcAddress(p->fn);
      if (a) found++;
      if (in(k_wrapped, NELEM(k_wrapped), p->fn)) note = "libEGL-wrapper";
      if (in(k_filtered, NELEM(k_filtered), p->fn)) note = "libEGL-filtered";
      if (!strcmp(layer, "both")) {
        vfn r = vgpa ? vgpa(p->fn) : NULL;
        printf("%s\t%s\tapp=%s\tvendor=%s\n", p->ext, p->fn, nn(a), vgpa ? nn(r) : "(no driver)");
        tsvf(T_PROCS, "%s\tapp\t%s\t%s\t%s\t%s\t\n", api, p->ext, p->fn, adv ? "yes" : "no", nn(a));
        tsvf(T_PROCS, "%s\tvendor\t%s\t%s\t%s\t%s\t\n", api, p->ext, p->fn, adv ? "yes" : "no",
             vgpa ? nn(r) : "no-driver");
      } else {
        printf("%s\t%s\tapp=%s%s%s\n", p->ext, p->fn, nn(a), note[0] ? "\t" : "", note);
        tsvf(T_PROCS, "%s\tapp\t%s\t%s\t%s\t%s\t%s\n", api, p->ext, p->fn, adv ? "yes" : "no", nn(a), note);
      }
    }
  }
  if (strcmp(layer, "vendor")) {
    /* Control: a name nobody implements. non-NULL here means NULL/non-NULL above says little. */
    const char *bogus = !strcmp(api, "egl") ? "eglRc2ProbeNoSuchFunction" : "glRc2ProbeNoSuchFunction";
    vfn a = eglGetProcAddress(bogus);
    printf("control\t%s\tapp=%s", bogus, nn(a));
    if (vgpa) printf("\tvendor=%s", nn(vgpa(bogus)));
    printf("\n");
    if (strcmp(api, "egl"))
      printf("app_gl_slots_used\t%d of 256%s\n", found,
             found >= 256 ? "\tWARNING: libEGL forwarder slots exhausted, later NULLs unreliable" : "");
  }
}

/* ------------------------------------------------------------------ limits */

struct lim { const char *name; GLenum e; char kind; int n; const char *gate; GLenum list; };

static void limits(const char *api, const char *gext, const struct lim *t, size_t nt) {
  for (size_t i = 0; i < nt; i++) {
    const struct lim *l = &t[i];
    char val[2048];
    if (l->gate && !has(gext, l->gate)) {
      snprintf(val, sizeof val, "n/a (no %s)", l->gate);
    } else {
      while (glGetError() != GL_NO_ERROR) {}
      GLint iv[4] = {-77777, -77777, -77777, -77777};
      GLfloat fv[4] = {-77777.f, -77777.f, -77777.f, -77777.f};
      if (l->kind == 'f') glGetFloatv(l->e, fv);
      else glGetIntegerv(l->e, iv);
      GLenum err = glGetError();
      if (err != GL_NO_ERROR) {
        snprintf(val, sizeof val, "(%s)", glerr(err));
      } else if (l->kind == 'f') {
        snprintf(val, sizeof val, "%g", fv[0]);
        for (int k = 1; k < l->n; k++) snprintf(val + strlen(val), sizeof val - strlen(val), " %g", fv[k]);
      } else if (l->kind == 'x') {
        snprintf(val, sizeof val, "0x%04x %s", (unsigned)iv[0], fmtname((unsigned)iv[0]));
      } else {
        snprintf(val, sizeof val, "%d", iv[0]);
        for (int k = 1; k < l->n; k++) snprintf(val + strlen(val), sizeof val - strlen(val), " %d", iv[k]);
      }
      printf("%s\t%s\n", l->name, val);
      tsvf(T_LIMITS, "%s\t%s\t%s\n", api, l->name, val);
      if (l->list && err == GL_NO_ERROR && iv[0] > 0 && iv[0] < 4096) {
        int cnt = iv[0];
        GLint *v = calloc(cnt + 4, sizeof *v);
        glGetIntegerv(l->list, v);
        GLenum e2 = glGetError();
        for (int k = 0; k < cnt; k++) {
          char nm[96];
          snprintf(nm, sizeof nm, "%s[%d]", l->name, k);
          if (e2 != GL_NO_ERROR) snprintf(val, sizeof val, "(%s)", glerr(e2));
          else snprintf(val, sizeof val, "0x%04x %s", (unsigned)v[k], fmtname((unsigned)v[k]));
          printf("%s\t%s\n", nm, val);
          tsvf(T_LIMITS, "%s\t%s\t%s\n", api, nm, val);
        }
        free(v);
      }
      continue;
    }
    printf("%s\t%s\n", l->name, val);
    tsvf(T_LIMITS, "%s\t%s\t%s\n", api, l->name, val);
  }
}

