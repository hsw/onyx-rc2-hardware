static void precision(void) {
  static const struct name sh[] = {{GL_VERTEX_SHADER, "vertex"}, {GL_FRAGMENT_SHADER, "fragment"}};
  static const struct name pt[] = {{GL_LOW_FLOAT, "LOW_FLOAT"}, {GL_MEDIUM_FLOAT, "MEDIUM_FLOAT"},
                                   {GL_HIGH_FLOAT, "HIGH_FLOAT"}, {GL_LOW_INT, "LOW_INT"},
                                   {GL_MEDIUM_INT, "MEDIUM_INT"}, {GL_HIGH_INT, "HIGH_INT"}};
  printf("shader\ttype\trange_min\trange_max\tprecision\n");
  for (size_t i = 0; i < NELEM(sh); i++)
    for (size_t j = 0; j < NELEM(pt); j++) {
      GLint r[2] = {-1, -1}, p = -1;
      while (glGetError() != GL_NO_ERROR) {}
      glGetShaderPrecisionFormat(sh[i].v, pt[j].v, r, &p);
      GLenum e = glGetError();
      char val[96];
      if (e) snprintf(val, sizeof val, "(%s)", glerr(e));
      else snprintf(val, sizeof val, "%d\t%d\t%d", r[0], r[1], p);
      printf("%s\t%s\t%s\n", sh[i].s, pt[j].s, val);
      for (char *c = val; *c; c++)
        if (*c == '\t') *c = ' ';
      tsvf(T_LIMITS, "gles2\tprecision.%s.%s\t%s\n", sh[i].s, pt[j].s, val);
    }
}

