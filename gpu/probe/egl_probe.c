static const char *g_tsv_dir;
static const char *k_tsv_names[] = {"configs", "extensions", "limits", "procs", "checks"};
static const char *k_tsv_heads[] = {
    NULL, /* configs: header written by the egl job */
    "api\textension\n",
    "api\tname\tvalue\n",
    "api\tlayer\textension\tfunction\tadvertised\tresult\tnote\n",
    "check\tresult\treason\n"};
static FILE *g_tsv[NELEM(k_tsv_names)];

static FILE *tsv(int i) {
  if (!g_tsv_dir) return NULL;
  if (!g_tsv[i]) {
    char p[512];
    snprintf(p, sizeof p, "%s/%s.tsv", g_tsv_dir, k_tsv_names[i]);
    g_tsv[i] = fopen(p, "a");
  }
  return g_tsv[i];
}
enum { T_CONFIGS, T_EXTS, T_LIMITS, T_PROCS, T_CHECKS };

static void tsvf(int i, const char *fmt, ...) {
  FILE *f = tsv(i);
  if (!f) return;
  va_list ap;
  va_start(ap, fmt);
  vfprintf(f, fmt, ap);
  va_end(ap);
}

static void tsv_close_all(void) {
  for (size_t i = 0; i < NELEM(g_tsv); i++)
    if (g_tsv[i]) { fclose(g_tsv[i]); g_tsv[i] = NULL; }
}

static void section(const char *name) { printf("\n## %s\n", name); }

static void list(const char *key, const char *s) {
  char buf[8192];
  printf("%s:\n", key);
  if (!s) { printf("  (null)\n"); return; }
  snprintf(buf, sizeof buf, "%s", s);
  for (char *t = strtok(buf, " "); t; t = strtok(NULL, " ")) printf("  %s\n", t);
}

static int has(const char *all, const char *ext) {
  size_t n = strlen(ext);
  for (const char *p = all; p && (p = strstr(p, ext)); p += n)
    if ((p == all || p[-1] == ' ') && (p[n] == ' ' || p[n] == 0)) return 1;
  return 0;
}

static int cmpstr(const void *a, const void *b) { return strcmp(*(char *const *)a, *(char *const *)b); }

/* Extensions sorted, one per line (also extensions.tsv with the api column). */
static void ext_section(const char *api, const char *s) {
  static char buf[16384];
  char *v[1024];
  int n = 0;
  if (!s) { printf("(null)\n"); return; }
  snprintf(buf, sizeof buf, "%s", s);
  for (char *t = strtok(buf, " "); t && n < (int)NELEM(v); t = strtok(NULL, " ")) v[n++] = t;
  qsort(v, n, sizeof v[0], cmpstr);
  for (int i = 0; i < n; i++) {
    printf("%s\n", v[i]);
    tsvf(T_EXTS, "%s\t%s\n", api, v[i]);
  }
  printf("count\t%d\n", n);
}

/* One line, tabs/newlines folded, for shader info logs. */
static const char *oneline(const char *s, char *out, size_t n) {
  size_t j = 0;
  for (size_t i = 0; s && s[i] && j + 1 < n; i++) {
    char c = s[i];
    if (c == '\n' || c == '\r' || c == '\t') {
      if (s[i + 1] && j > 0 && out[j - 1] != ' ') out[j++] = ' ';
      continue;
    }
    out[j++] = c;
  }
  out[j] = 0;
  if (j == 0) snprintf(out, n, "(empty)");
  return out;
}

