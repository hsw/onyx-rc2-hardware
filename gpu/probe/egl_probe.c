static void check(const char *name, const char *res, const char *fmt, ...) {
  char r[1024];
  va_list ap;
  va_start(ap, fmt);
  vsnprintf(r, sizeof r, fmt, ap);
  va_end(ap);
  printf("check\t%s\t%s\t%s\n", name, res, r);
  tsvf(T_CHECKS, "%s\t%s\t%s\n", name, res, r);
}

static GLuint shader(GLenum type, const char *src, char *log, size_t n) {
  GLuint s = glCreateShader(type);
  GLint ok = 0;
  char raw[1024] = "";
  glShaderSource(s, 1, &src, NULL);
  glCompileShader(s);
  glGetShaderiv(s, GL_COMPILE_STATUS, &ok);
  glGetShaderInfoLog(s, sizeof raw, NULL, raw);
  oneline(raw, log, n);
  if (!ok) { glDeleteShader(s); return 0; }
  return s;
}

static const char *k_vs = "attribute vec2 p; varying vec2 v;\n"
                          "void main() { v = p * 0.5 + 0.5; gl_Position = vec4(p, 0.0, 1.0); }\n";
static const char *k_fs_tex = "precision mediump float; uniform sampler2D s; varying vec2 v;\n"
                              "void main() { gl_FragColor = texture2D(s, v); }\n";

static GLuint program(const char *vs, const char *fs, char *log, size_t n) {
  GLuint a = shader(GL_VERTEX_SHADER, vs, log, n);
  if (!a) return 0;
  GLuint b = shader(GL_FRAGMENT_SHADER, fs, log, n);
  if (!b) return 0;
  GLuint p = glCreateProgram();
  glAttachShader(p, a);
  glAttachShader(p, b);
  glBindAttribLocation(p, 0, "p");
  glLinkProgram(p);
  GLint ok = 0;
  char raw[1024] = "";
  glGetProgramiv(p, GL_LINK_STATUS, &ok);
  glGetProgramInfoLog(p, sizeof raw, NULL, raw);
  oneline(raw, log, n);
  return ok ? p : 0;
}

static int job_fbo(void) {
  struct env e;
  if (!env_make(&e, 2)) { check("fbo", "FAIL", "no ES2 context"); return 1; }
  struct { const char *name, *gate; GLenum color_rb, depth, stencil, packed; int depth_tex; } t[] = {
      {"fbo-rgba8-texture", 0, 0, 0, 0, 0, 0},
      {"fbo-rgba8-renderbuffer", "GL_OES_rgb8_rgba8", 0x8058, 0, 0, 0, 0},
      {"fbo-rgb8-renderbuffer", "GL_OES_rgb8_rgba8", 0x8051, 0, 0, 0, 0},
      {"fbo-rgb565-renderbuffer", 0, 0x8D62, 0, 0, 0, 0},
      {"fbo-rgba4-renderbuffer", 0, 0x8056, 0, 0, 0, 0},
      {"fbo-rgb5a1-renderbuffer", 0, 0x8057, 0, 0, 0, 0},
      {"fbo-rgba8tex+depth16", 0, 0, 0x81A5, 0, 0, 0},
      {"fbo-rgba8tex+depth24", "GL_OES_depth24", 0, 0x81A6, 0, 0, 0},
      {"fbo-rgba8tex+stencil8", 0, 0, 0, 0x8D48, 0, 0},
      {"fbo-rgba8tex+depth16+stencil8", 0, 0, 0x81A5, 0x8D48, 0, 0},
      {"fbo-rgba8tex+depth24stencil8", "GL_OES_packed_depth_stencil", 0, 0, 0, 0x88F0, 0},
      {"fbo-rgba8tex+depth-texture16", "GL_OES_depth_texture", 0, 0, 0, 0, 1},
  };
  for (size_t i = 0; i < NELEM(t); i++) {
    if (t[i].gate && !has(e.gext, t[i].gate)) {
      check(t[i].name, "SKIP", "not advertised: %s", t[i].gate);
      continue;
    }
    while (glGetError() != GL_NO_ERROR) {}
    GLuint fb, tex = 0, dtex = 0, rb[3] = {0, 0, 0};
    glGenFramebuffers(1, &fb);
    glBindFramebuffer(GL_FRAMEBUFFER, fb);
    glGenRenderbuffers(3, rb);
    if (t[i].color_rb) {
      glBindRenderbuffer(GL_RENDERBUFFER, rb[0]);
      glRenderbufferStorage(GL_RENDERBUFFER, t[i].color_rb, PB_W, PB_H);
      glFramebufferRenderbuffer(GL_FRAMEBUFFER, GL_COLOR_ATTACHMENT0, GL_RENDERBUFFER, rb[0]);
    } else {
      glGenTextures(1, &tex);
      glBindTexture(GL_TEXTURE_2D, tex);
      glTexImage2D(GL_TEXTURE_2D, 0, GL_RGBA, PB_W, PB_H, 0, GL_RGBA, GL_UNSIGNED_BYTE, NULL);
      glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MIN_FILTER, GL_NEAREST);
      glFramebufferTexture2D(GL_FRAMEBUFFER, GL_COLOR_ATTACHMENT0, GL_TEXTURE_2D, tex, 0);
    }
    if (t[i].depth) {
      glBindRenderbuffer(GL_RENDERBUFFER, rb[1]);
      glRenderbufferStorage(GL_RENDERBUFFER, t[i].depth, PB_W, PB_H);
      glFramebufferRenderbuffer(GL_FRAMEBUFFER, GL_DEPTH_ATTACHMENT, GL_RENDERBUFFER, rb[1]);
    }
    if (t[i].stencil) {
      glBindRenderbuffer(GL_RENDERBUFFER, rb[2]);
      glRenderbufferStorage(GL_RENDERBUFFER, t[i].stencil, PB_W, PB_H);
      glFramebufferRenderbuffer(GL_FRAMEBUFFER, GL_STENCIL_ATTACHMENT, GL_RENDERBUFFER, rb[2]);
    }
    if (t[i].packed) {
      glBindRenderbuffer(GL_RENDERBUFFER, rb[1]);
      glRenderbufferStorage(GL_RENDERBUFFER, t[i].packed, PB_W, PB_H);
      glFramebufferRenderbuffer(GL_FRAMEBUFFER, GL_DEPTH_ATTACHMENT, GL_RENDERBUFFER, rb[1]);
      glFramebufferRenderbuffer(GL_FRAMEBUFFER, GL_STENCIL_ATTACHMENT, GL_RENDERBUFFER, rb[1]);
    }
    if (t[i].depth_tex) {
      glGenTextures(1, &dtex);
      glBindTexture(GL_TEXTURE_2D, dtex);
      glTexImage2D(GL_TEXTURE_2D, 0, GL_DEPTH_COMPONENT, PB_W, PB_H, 0, GL_DEPTH_COMPONENT, GL_UNSIGNED_SHORT, NULL);
      glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MIN_FILTER, GL_NEAREST);
      glFramebufferTexture2D(GL_FRAMEBUFFER, GL_DEPTH_ATTACHMENT, GL_TEXTURE_2D, dtex, 0);
    }
    GLenum setup_err = glGetError();
    GLenum st = glCheckFramebufferStatus(GL_FRAMEBUFFER);
    GLenum draw_err = 0;
    if (st == GL_FRAMEBUFFER_COMPLETE) {
      glViewport(0, 0, PB_W, PB_H);
      glClearColor(0.f, 1.f, 0.f, 1.f);
      glClearDepthf(1.f);
      glClearStencil(0);
      glClear(GL_COLOR_BUFFER_BIT | GL_DEPTH_BUFFER_BIT | GL_STENCIL_BUFFER_BIT);
      GLubyte px[4] = {0, 0, 0, 0};
      glReadPixels(PB_W / 2, PB_H / 2, 1, 1, GL_RGBA, GL_UNSIGNED_BYTE, px);
      glFinish();
      draw_err = glGetError();
      int green = px[1] > 200 && px[0] < 50;
      check(t[i].name, !setup_err && !draw_err && green ? "PASS" : "FAIL",
            "status %s; setup %s; clear+read %s; pixel %02x%02x%02x%02x", fboname(st), glerr(setup_err),
            glerr(draw_err), px[0], px[1], px[2], px[3]);
    } else {
      check(t[i].name, "FAIL", "status %s; setup %s", fboname(st), glerr(setup_err));
    }
    glBindFramebuffer(GL_FRAMEBUFFER, 0);
    glDeleteFramebuffers(1, &fb);
    glDeleteRenderbuffers(3, rb);
    if (tex) glDeleteTextures(1, &tex);
    if (dtex) glDeleteTextures(1, &dtex);
  }
  env_free(&e);
  return 0;
}

/* Draw the bound texture over the pbuffer, return whether the centre pixel is the texture's red. */
static int sampled_red(GLuint prog, GLubyte px[4]) {
  static const GLfloat q[] = {-1, -1, 1, -1, -1, 1, 1, 1};
  glBindFramebuffer(GL_FRAMEBUFFER, 0);
  glViewport(0, 0, PB_W, PB_H);
  glClearColor(0.f, 0.f, 1.f, 1.f);
  glClear(GL_COLOR_BUFFER_BIT);
  glUseProgram(prog);
  glUniform1i(glGetUniformLocation(prog, "s"), 0);
  glEnableVertexAttribArray(0);
  glVertexAttribPointer(0, 2, GL_FLOAT, GL_FALSE, 0, q);
  glDrawArrays(GL_TRIANGLE_STRIP, 0, 4);
  glReadPixels(PB_W / 2, PB_H / 2, 1, 1, GL_RGBA, GL_UNSIGNED_BYTE, px);
  glFinish();
  return px[0] > 200 && px[1] < 50 && px[2] < 50;
}

static int job_npot(void) {
  struct env e;
  if (!env_make(&e, 2)) { check("npot", "FAIL", "no ES2 context"); return 1; }
  char log[512];
  GLuint prog = program(k_vs, k_fs_tex, log, sizeof log);
  if (!prog) { check("npot", "FAIL", "test program: %s", log); env_free(&e); return 1; }
  int npot = has(e.gext, "GL_OES_texture_npot") || has(e.gext, "GL_ARB_texture_non_power_of_two");
  struct { const char *name; int w, h, repeat, mip; int expect; } t[] = {
      {"pot-64x64-mipmap (control)", 64, 64, 0, 1, 1},
      {"npot-100x60-clamp-nomip", 100, 60, 0, 0, 1},
      {"npot-100x60-repeat-nomip", 100, 60, 1, 0, npot},
      {"npot-100x60-clamp-mipmap", 100, 60, 0, 1, npot},
  };
  for (size_t i = 0; i < NELEM(t); i++) {
    int w = t[i].w, h = t[i].h;
    GLubyte *red = malloc((size_t)w * h * 4);
    for (int k = 0; k < w * h; k++) { red[4 * k] = 255; red[4 * k + 1] = 0; red[4 * k + 2] = 0; red[4 * k + 3] = 255; }
    while (glGetError() != GL_NO_ERROR) {}
    GLuint tex;
    glGenTextures(1, &tex);
    glActiveTexture(GL_TEXTURE0);
    glBindTexture(GL_TEXTURE_2D, tex);
    glPixelStorei(GL_UNPACK_ALIGNMENT, 1);
    glTexImage2D(GL_TEXTURE_2D, 0, GL_RGBA, w, h, 0, GL_RGBA, GL_UNSIGNED_BYTE, red);
    free(red);
    GLenum up = glGetError(), gm = GL_NO_ERROR;
    GLenum wrap = t[i].repeat ? GL_REPEAT : GL_CLAMP_TO_EDGE;
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_WRAP_S, wrap);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_WRAP_T, wrap);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MAG_FILTER, GL_LINEAR);
    if (t[i].mip) {
      glGenerateMipmap(GL_TEXTURE_2D);
      gm = glGetError();
      glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MIN_FILTER, GL_LINEAR_MIPMAP_LINEAR);
    } else {
      glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MIN_FILTER, GL_LINEAR);
    }
    GLubyte px[4] = {0, 0, 0, 0};
    int ok = sampled_red(prog, px);
    GLenum de = glGetError();
    check(t[i].name, ok ? "PASS" : "FAIL",
          "%s (pixel %02x%02x%02x%02x); upload %s%s%s; draw %s; expected %s (%s)",
          ok ? "sampled" : "not sampled (incomplete texture)", px[0], px[1], px[2], px[3], glerr(up),
          t[i].mip ? "; glGenerateMipmap " : "", t[i].mip ? glerr(gm) : "", glerr(de),
          t[i].expect ? "sampled" : "not sampled",
          (w & (w - 1)) == 0 ? "POT" : npot ? "GL_OES_texture_npot advertised" : "ES2 core NPOT limits");
    glDeleteTextures(1, &tex);
  }
  env_free(&e);
  return 0;
}

